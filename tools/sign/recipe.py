"""Writes the recipe the mod applies to the sign's models (src/client/features/sign/SignData.h): for each model the
original it expects (its vertex and triangle counts and the CRC-32 of its geometry), then the operations that build the
new geometry from it: "copy these triangles, moved" and "these new vertices and triangles" (colours as weights of the
original's vertices). And our collision (COL3) for both models, with the CRC-32 of the originals it replaces.

python3 recipe.py <path of SignData.h>"""
import struct
import sys
import zlib

import numpy as np

sys.path.insert(0, ".")
import build
import rw
from world import cols


def geometry_crc(g):
    so, ss, _ = rw.find(g.raw, 12, len(g.raw), rw.CHUNK_STRUCT)
    return zlib.crc32(g.raw[so:so + ss])


def model_recipe(model_id, src, out, colour=None):
    r = struct.pack("<IIII", model_id, len(src.verts), len(src.tris), geometry_crc(src))
    r += struct.pack("<B4BxxxI", 1 if colour else 0, *(colour or (0, 0, 0, 0)), len(out.ops))
    for op in out.ops:
        if op[0] == "copy":
            _, tris, move, fix = op
            r += struct.pack("<B3x3fI", 0, *move, len(tris))
            r += np.asarray(tris, np.uint16).tobytes().ljust((len(tris) * 2 + 3) // 4 * 4, b"\0")
            r += struct.pack("<I", len(fix))
            for v, z in sorted(fix.items()):
                r += struct.pack("<H2xf", v, z)
        else:
            _, verts, tris = op
            r += struct.pack("<B3xI", 1, len(verts))
            for p, uv, w in verts:
                r += struct.pack("<5fI", *p, *uv, len(w))
                for s, wt in w:
                    r += struct.pack("<H2xf", s, wt)
            r += struct.pack("<I", len(tris))
            for a, b, c, m in tris:
                r += struct.pack("<4H", a, b, c, m)
    return r


def col_body(raw):
    """the part LoadCollisionModelVer3 reads: after the 32-byte header, header.size - 24 bytes"""
    size = struct.unpack_from("<I", raw, 4)[0]
    return raw[32:32 + size - 24]


def c_array(name, data):
    lines = ["alignas(4) inline constexpr unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main(path):
    ob, oa = build.build_sign()
    ol = build.build_lod()
    blob = b"NSR1" + struct.pack("<I", 3)
    blob += model_recipe(13831, build.B, ob)
    blob += model_recipe(13722, build.A, oa)
    blob += model_recipe(13759, build.L, ol, build.cream_of_lod() + (255,))
    c01, c = build.build_col(oa)
    orig = cols()
    o01, o = col_body(orig["vinesign1_cunte01"].raw), col_body(orig["vinesign1_cunte"].raw)
    text = [
        "// Generated by tools/sign/recipe.py from the game's own VineSign1_cunte models: do not edit.",
        "// NOSTALGIA in place of VINEWOOD. The recipe holds no data of the game's: copies are triangle numbers",
        "// of the originals (moved), the new letters are ours; the collision is ours.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace coop::sign::data {",
        "",
        "inline constexpr uint32_t kColLettersCrc = 0x%08x, kColLettersSize = %d;  // VineSign1_cunte01's, original"
        % (zlib.crc32(o01), len(o01)),
        "inline constexpr uint32_t kColFramesCrc = 0x%08x, kColFramesSize = %d;   // VineSign1_cunte's, original"
        % (zlib.crc32(o), len(o)),
        "",
        c_array("kRecipe", blob),
        "",
        c_array("kColLetters", col_body(c01)),
        "",
        c_array("kColFrames", col_body(c)),
        "",
        "}  // namespace coop::sign::data",
        "",
    ]
    open(path, "w").write("\n".join(text))
    print("recipe %d bytes, collision %d + %d" % (len(blob), len(col_body(c01)), len(col_body(c))))


if __name__ == "__main__":
    main(sys.argv[1])
